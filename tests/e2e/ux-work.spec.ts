import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { createState, execute } from "../../src/lib/engine";
import type { StoreState } from "../../src/lib/types";

test("work UI retains drafts during saves and wires dedicated task, milestone and file commands", async ({ page }) => {
  test.skip(process.env.CREWMORI_UX_TEST !== "true", "Local UX runner uses intercepted APIs and never a real account.");
  let state: StoreState = createState("active_paid_project");
  state.mode = "connected";
  state.tables.owners.owner_alya.display_name = "Rani";
  const seen: string[] = [];
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.route("**/api/**", async (route) => {
    const url = new URL(route.request().url());
    if (url.pathname === "/api/workspace/state") return route.fulfill({ json: { state } });
    if (url.pathname === "/api/auth/user") return route.fulfill({ json: { user: { id: "owner_alya", email: "rani@example.test" } } });
    if (url.pathname === "/api/commands") {
      const command = route.request().postDataJSON();
      seen.push(command.type);
      if (command.type === "task.save") await new Promise((resolve) => setTimeout(resolve, 850));
      const outcome = execute(state, command.type, { ...command.input, idempotency_key: command.idempotencyKey });
      if (outcome.result.ok) state = outcome.state;
      return route.fulfill({ status: outcome.result.ok ? 200 : 422, json: outcome.result.ok ? { result: outcome.result } : { error: { code: outcome.result.code, message: outcome.result.message } } });
    }
    if (url.pathname === "/api/files" && route.request().method() === "POST") return route.fulfill({ json: { id: randomUUID(), name: "notes.txt", type: "text/plain", size: 25, sha256: "controlled-file-hash" } });
    return route.fulfill({ status: 500, json: { error: { code: "UNEXPECTED_TEST_REQUEST", message: `Unexpected test request: ${url.pathname}` } } });
  });
  await page.goto("/app/projects/project_northstar?tab=tasks");
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("button", { name: "Save task", exact: true }).click();
  await expect(dialog.getByLabel("Task name", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await expect(dialog.getByLabel("Task name", { exact: true })).toBeFocused();
  await dialog.getByLabel("Task name", { exact: true }).fill("Review source data");
  await dialog.getByLabel("Details", { exact: true }).fill("Keep the agreed source assumptions.");
  await expect(dialog.getByLabel("Responsible", { exact: true }).locator("option:checked")).toHaveText("Rani — you");
  const submit = dialog.locator("button[type=submit]");
  await submit.click();
  await expect(submit).toBeDisabled();
  await expect(dialog.getByLabel("Task name", { exact: true })).toBeDisabled();
  await expect(dialog.getByRole("button", { name: "Cancel", exact: true })).toBeDisabled();
  await expect(dialog).toHaveCount(0);
  expect(seen.filter((type) => type === "task.save")).toHaveLength(1);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Review source data", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add milestone", exact: true }).click();
  await dialog.getByLabel("Milestone name", { exact: true }).fill("Source review milestone");
  await dialog.getByLabel("Target date", { exact: true }).fill("2026-10-20");
  await dialog.getByLabel("Review source data", { exact: true }).check();
  await dialog.getByRole("button", { name: "Save milestone", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(seen).toContain("milestone.save");
  const savedTask = Object.values(state.tables.work_tasks).find((task) => task.title === "Review source data")!;
  const savedMilestone = Object.values(state.tables.milestones).find((milestone) => milestone.title === "Source review milestone")!;
  expect(savedTask.milestone_id).toBe(savedMilestone.id);
  await page.getByRole("link", { name: "files", exact: true }).click();
  await page.getByRole("button", { name: "Add files", exact: true }).click();
  await dialog.getByLabel("Or add an external file link", { exact: true }).fill("https://example.test/reference");
  await dialog.getByLabel("File name", { exact: true }).fill("Reference brief");
  await dialog.getByRole("button", { name: "Add files", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(seen).toContain("file.link");
  await expect(page.getByRole("link", { name: "Open external link", exact: true })).toHaveAttribute("href", "https://example.test/reference");
  await page.getByRole("button", { name: "Add files", exact: true }).click();
  await dialog.getByLabel("Upload files", { exact: true }).setInputFiles({ name: "notes.txt", mimeType: "text/plain", buffer: Buffer.from("Reviewed source data notes") });
  await dialog.getByRole("button", { name: "Add files", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  expect(seen).toContain("file.attach");
  await page.reload();
  await expect(page.getByRole("heading", { name: "notes.txt", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/app/projects/project_northstar?tab=tasks");
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  const bounds = await dialog.boundingBox();
  expect(bounds).not.toBeNull();
  expect(bounds!.x).toBeGreaterThanOrEqual(0);
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(391);
  await expect(dialog.locator("button[type=submit]")).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
